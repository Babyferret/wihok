"""Write THIRD-PARTY-NOTICES.txt: the licenses of the libraries that end up inside the installer.

Run with the project's Python (the CUDA one, which has the most packages):
    python packaging/make_notices.py
It starts from the libraries Wihok imports and follows their dependencies, then copies each package's
license name and license files from the installed metadata. Review the result; it reports a package
whose license files it could not find.
"""
import re
import sys
from importlib import metadata
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "THIRD-PARTY-NOTICES.txt"

# What Wihok imports directly. Everything these need is followed from here.
START = ["torch", "torchaudio", "demucs", "librosa", "numpy", "soundfile", "PySide6", "huggingface_hub", "PyYAML"]
# Installed only to build or test; never bundled.
SKIP = {"pytest", "pyinstaller", "pyinstaller-hooks-contrib", "altgraph", "pefile", "pywin32-ctypes", "setuptools",
        "pluggy", "iniconfig", "colorama", "pygments", "packaging",
        "PySide6_WebEngine"}  # installed with PySide6 but not part of the packaged app (checked in the build folders)
LICENSE_FILE = re.compile(r"(?i)(^|[\\/])(licen[sc]es?|copying|notice|copyright)[^\\/]*$")


def normal(name: str) -> str:
    return re.sub(r"[-_.]+", "-", name).lower()


def requirements(dist) -> list[str]:
    names = []
    for line in dist.requires or []:
        if "extra ==" in line:  # optional extras are not installed with the app
            continue
        match = re.match(r"\s*([A-Za-z0-9][A-Za-z0-9._-]*)", line)
        if match:
            names.append(match.group(1))
    return names


def collect() -> dict:
    found, queue = {}, list(START)
    while queue:
        name = queue.pop()
        key = normal(name)
        if key in found or key in {normal(s) for s in SKIP}:
            continue
        try:
            dist = metadata.distribution(name)
        except metadata.PackageNotFoundError:
            continue
        found[key] = dist
        queue.extend(requirements(dist))
    return found


def license_name(dist) -> str:
    meta = dist.metadata
    expression = meta.get("License-Expression")
    if expression:
        return expression
    text = (meta.get("License") or "").strip()
    if text and len(text) < 80 and "\n" not in text:
        return text
    classifiers = [c.split("::")[-1].strip() for c in meta.get_all("Classifier") or [] if c.startswith("License ::")]
    return ", ".join(classifiers) or (text.splitlines()[0][:80] if text else "see the license files below")


def license_files(dist) -> list[tuple[str, str]]:
    files = []
    for f in dist.files or []:
        if LICENSE_FILE.search(str(f)):
            path = Path(dist.locate_file(f))
            if path.is_file() and path.stat().st_size < 400_000:
                files.append((str(f).replace("\\", "/"), path.read_text(encoding="utf-8", errors="replace").strip()))
    return files


def main() -> int:
    packages = collect()
    lines = [
        "THIRD-PARTY NOTICES",
        "===================",
        "",
        "Wihok itself is MIT licensed (see LICENSE). It includes or uses the libraries below, each under its own",
        "license, which is reproduced after the list. This file is generated by packaging/make_notices.py.",
        "",
        "Not covered by the list below:",
        " - The bundled font TA GBA monothai MAX (SIL Open Font License 1.1): see assets/fonts/OFL.txt.",
        " - Qt (through PySide6) is used under the GNU LGPL v3. It is linked dynamically: its DLLs are separate",
        "   files in the install folder and can be replaced. Source code for Qt is available from https://www.qt.io.",
        " - The GPU add-on contains NVIDIA CUDA and cuDNN runtime libraries (cuBLAS, cuFFT, cuSPARSE, cuSOLVER,",
        "   cuRAND, NVRTC, cuDNN and others) taken unchanged from the PyTorch distribution. They are NVIDIA software,",
        "   not covered by the MIT license above. They are redistributed as part of this application under the",
        "   NVIDIA CUDA Toolkit EULA (Attachment A) and the cuDNN license: object code only, unmodified, used only",
        "   by Wihok, on systems with NVIDIA GPUs. The add-on installs only over an existing Wihok installation.",
        " - lameenc (LAME, LGPL-3.0) and soxr (LGPL-2.1) are used as separate library files in the install folder,",
        "   so they can be replaced by the user. Their source code is available from their project pages.",
        " - The Demucs separation model weights are not shipped. The app downloads them from",
        "   https://huggingface.co/adefossez/HTDemucs; their license is stated by the author to be unclear.",
        "",
        "Libraries",
        "---------",
    ]
    missing = []
    for key in sorted(packages):
        dist = packages[key]
        lines.append(f"{dist.metadata['Name']} {dist.version} - {license_name(dist)}")
    lines.append("")
    for key in sorted(packages):
        dist = packages[key]
        files = license_files(dist)
        lines += ["", "=" * 78, f"{dist.metadata['Name']} {dist.version} - {license_name(dist)}", "=" * 78]
        if not files:
            missing.append(dist.metadata["Name"])
            lines.append("(no license file found in the installed package)")
        for name, text in files:
            lines += ["", f"--- {name} ---", text]
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {OUT.name}: {len(packages)} libraries, {OUT.stat().st_size / 1024:.0f} KB")
    if missing:
        print("no license file found for:", ", ".join(missing))
    return 0


if __name__ == "__main__":
    sys.exit(main())
